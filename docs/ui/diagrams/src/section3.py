def _matrix(d, caption, states, matrix, first_w):
    cw = (9355 - first_w) // len(states)
    widths = [first_w] + [cw] * len(states)
    widths[0] += 9355 - sum(widths)
    header = [{"t": "Раздел / команда"}] + [{"t": s} for s in states]
    rows = []
    for name, avail in matrix:
        if avail is None:
            rows.append([{"t": name, "b": True, "span": len(states) + 1, "fill": "F7F7F7"}])
            continue
        r = [name]
        for s in states:
            if s in avail:
                r.append({"t": avail[s], "jc": "center", "sz": 22})
            else:
                r.append({"t": "–", "jc": "center", "fill": GRAY, "color": "A6A6A6", "sz": 22})
        rows.append(r)
    d.table(caption, widths, header, rows)
