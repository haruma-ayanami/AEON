# Граф состояний главного меню: пользователь
from nav import *
g = Graph(1840, 1250)
CX0, CY0, CX1, CY1 = 330, 175, 1810, 1065
g.extra.append(f'<rect x="{CX0}" y="{CY0}" width="{CX1-CX0}" height="{CY1-CY0}" rx="30" fill="#FBFBFB" stroke="{BLUE}" stroke-width="2.6"/>')
g.extra.append(f'<line x1="{CX0}" y1="{CY0+52}" x2="{CX1}" y2="{CY0+52}" stroke="{BLUE}" stroke-width="1.6"/>')
g.extra.append(f'<text x="{CX1-26}" y="{CY0+36}" text-anchor="end" font-size="25" font-weight="bold" fill="{BLUE}">Работа авторизованного пользователя</text>')
S = dict(kind="state", w=236)
g.box("m0", 150, 640, "M0. Гость", "Ф1, Ф2", kind="state", w=220)
g.box("m3", 470, 85, "M3. Отправка (модальное)", "Ф5, Ф6", kind="state", w=330)
g.box("m1", 510, 390, "M1. Кошелёк", "Ф3, Ф4, Ф7", **S)
g.box("m2", 880, 390, "M2. История", "Ф8, Ф9", **S)
g.box("m10", 1250, 390, "M10. Уведомления", "Ф17", **S)
g.box("m11", 1620, 390, "M11. Профиль", "Ф18", **S)
g.box("m4", 510, 650, "M4. Маркетплейс", "Ф10, Ф12", **S)
g.box("m5", 880, 650, "M5. Объявление", "Ф11", **S)
g.box("m6", 1250, 650, "M6. Сделка", "Ф13", **S)
g.box("m7", 1620, 650, "M7. Мои сделки", "Ф14", **S)
g.box("m8", 510, 910, "M8. Мои объявления", "Ф15", **S)
g.box("m9", 880, 910, "M9. Редактор объявления", "Ф16", **S)
I = g.items
# переходы по командам разделов меню – с границы составного состояния
for k, lab in (("m1", "1"), ("m2", "2"), ("m10", "6"), ("m11", "7")):
    b = I[k]
    x = b.cx + (55 if k == "m1" else 0)
    g.e(k, k, lab, start=(x, CY0 + 52), end=(x, b.y0), lpos=(x, (CY0 + 52 + b.y0) / 2))
for k, lab in (("m4", "3"), ("m8", "5")):
    b = I[k]
    g.e(k, k, lab, start=(CX0, b.cy), end=(b.x0, b.cy), lpos=((CX0 + b.x0) / 2, b.cy))
b = I["m7"]; g.e("m7", "m7", "4", start=(CX1, b.cy), end=(b.x1, b.cy), lpos=((CX1 + b.x1) / 2, b.cy))
b = I["m9"]; g.e("m9", "m9", "5A", start=(b.cx, CY1), end=(b.cx, b.y1), lpos=(b.cx, (CY1 + b.y1) / 2))
# вход, выход, модальное состояние
g.e("m0", "m1", "0", t=0.3)
g.e("m0", "m0", "8", start=(CX0, 830), end=(I["m0"].cx + 40, I["m0"].y1), points=[(I["m0"].cx + 40, 830)], lpos=(250, 830))
m1, m3 = I["m1"], I["m3"]
g.e("m1", "m3", "1C / 1F, 9", both=True, start=(m1.cx - 60, m1.y0), end=(m1.cx - 60, m3.y1), lpos=(m1.cx - 60, CY0 + 110))
# контекстные команды
g.e("m4", "m5", "3B / 3C, 9", both=True, lpos=(695, 650 - 34))
g.e("m5", "m6", "3D", lpos=(1065, 650 - 34))
g.e("m7", "m6", "4B / 9", both=True, lpos=(1435, 650 - 34))
g.e("m8", "m9", "5B / 5C, 9", both=True, lpos=(695, 910 - 34))
g.e("m10", "m2", "6A", lpos=(1065, 390 - 34))
g.e("m10", "m6", "6A")
g.extra.append(note(40, 1110, 1760, [
    "Команды разделов «Кошелёк», «P2P», «Уведомления» и «Профиль» (1–7, 5A) доступны в любом вложенном состоянии;",
    "в модальном состоянии M3 они недоступны до подтверждения (1F) или отмены (9) операции; команда 8 – выход."]))
print(*g.save("g1"))
